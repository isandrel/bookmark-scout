/// <reference types="bun" />
/**
 * Writes the hosting files that hold config values into `public/` before dev and build, so
 * they are never typed by hand: Cloudflare Pages' `_redirects` and `.well-known/security.txt`
 * (RFC 9116). Both outputs are git-ignored.
 *
 *   bun scripts/generate-public-files.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { PUBLIC_PATHS, type Site, site } from "@bookmark-scout/config";
import { LEGACY_DOCS_REDIRECTS } from "../lib/content/docs-redirects";
import { formatRedirects, type RedirectRule } from "../lib/redirects";

/**
 * Permanent redirects for URLs the site no longer serves:
 * - the old `/<locale>/docs/...` pages (every language, with and without the trailing slash)
 *   to their page on the docs site;
 * - the default language's old prefix, `/en/...`, to the unprefixed page (`/en/privacy/` to
 *   `/privacy/`), last, because it is the only splat rule.
 * Nothing redirects by browser language: `/` is the default language's home for everyone.
 */
export function redirectRules(model: Site = site): RedirectRule[] {
    const docs = model.locales.supported.flatMap((locale) =>
        Object.entries(LEGACY_DOCS_REDIRECTS).flatMap(([path, target]) => {
            const from = `/${locale}/docs${path ? `/${path}` : ""}`;
            const to = model.docs.url(target);
            return [
                { from, to, status: 301 as const },
                { from: `${from}/`, to, status: 301 as const },
            ];
        }),
    );
    const oldDefault = `/${model.locales.default}`;
    return [
        ...docs,
        { from: oldDefault, to: model.url.path(model.locales.default), status: 301 },
        { from: `${oldDefault}/*`, to: "/:splat", status: 301 },
    ];
}

/** Cloudflare Pages `_redirects`. */
export function redirectsFile(model: Site = site): string {
    return formatRedirects(redirectRules(model), [
        "Cloudflare Pages redirects, generated by scripts/generate-public-files.ts from config.",
        "scripts/serve-out.ts applies the same file in browser tests.",
    ]);
}

/** RFC 9116 security.txt. Renew `[security_txt] expires` in config/web.toml before it lapses. */
export function securityTxtFile(model: Site = site): string {
    return [
        `# ${model.name} security contact (RFC 9116), generated from config/project.toml and config/web.toml.`,
        `Contact: ${model.contact.mailto("security")}`,
        `Contact: ${model.repo.newSecurityAdvisory}`,
        `Expires: ${model.securityTxt.expires}`,
        `Preferred-Languages: ${model.locales.supported.join(", ")}`,
        `Canonical: ${model.securityTxt.url}`,
        `Policy: ${model.repo.file("SECURITY.md")}`,
        "",
    ].join("\n");
}

/** Output path (under `public/`) and contents of every generated file. */
export const PUBLIC_FILES: Record<string, () => string> = {
    _redirects: () => redirectsFile(),
    [PUBLIC_PATHS.securityTxt.slice(1)]: () => securityTxtFile(),
};

if (import.meta.main) {
    const publicDir = resolve(import.meta.dir, "..", "public");
    for (const [path, render] of Object.entries(PUBLIC_FILES)) {
        const file = join(publicDir, path);
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, render());
        console.log(`public/${path}`);
    }
}
